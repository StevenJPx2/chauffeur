#!/usr/bin/env node
// The chauffeur-next Homebrew formula for a release candidate, rendered from
// its SHA256SUMS:
//
//   node scripts/homebrew.mjs 1.0.0-rc.1 dist/SHA256SUMS > Formula/chauffeur-next.rb
//
// Every target's checksum comes from the run that built the tarballs, so the
// formula is generated, never edited by hand. A third argument replaces the
// download location, such as a local folder's file:// URL for testing.

import { readFileSync } from "node:fs"
import { resolve } from "node:path"
import { fileURLToPath } from "node:url"
import { tarballName } from "./package.mjs"

const REPOSITORY = "https://github.com/StevenJPx2/chauffeur"
const DOWNLOADS = `${REPOSITORY}/releases/download`

/** Homebrew's OS and CPU blocks for each target, in the order they render. */
const PLATFORMS = [
  { os: "macos", cpu: "arm", target: "darwin-arm64" },
  { os: "macos", cpu: "intel", target: "darwin-x64" },
  { os: "linux", cpu: "arm", target: "linux-arm64" },
  { os: "linux", cpu: "intel", target: "linux-x64" },
]

/** `SHA256SUMS` as a map from file name to checksum. */
export function parseSums(text) {
  const sums = new Map()

  for (const line of text.split("\n").filter((line) => line.trim() !== "")) {
    const match = line.match(/^([0-9a-f]{64}) [ *]?(\S+)$/)

    if (!match) throw new Error(`not a SHA256SUMS line: ${line}`)
    sums.set(match[2], match[1])
  }

  return sums
}

function platforms(os, release, sums, downloads) {
  return PLATFORMS.filter((platform) => platform.os === os)
    .map(({ cpu, target }) => {
      const name = tarballName(release, target)
      const sha256 = sums.get(name)

      if (!sha256) throw new Error(`SHA256SUMS has no ${name}`)

      return [
        `    on_${cpu} do`,
        `      url "${downloads}/${name}"`,
        `      sha256 "${sha256}"`,
        "    end",
      ].join("\n")
    })
    .join("\n")
}

/**
 * The formula for release candidate `release`. Formula and binary are both
 * chauffeur-next, so the candidate keeps its own socket and configuration
 * beside an installed chauffeur, and finds its shipped content in
 * share/chauffeur-next/, which is the formula's pkgshare.
 */
export function formula(release, sums, downloads = `${DOWNLOADS}/v${release}`) {
  if (!/^\d+\.\d+\.\d+-rc\.\d+$/.test(release)) throw new Error(`chauffeur-next needs a release candidate, not ${release}`)

  return `# Generated by scripts/homebrew.mjs in ${REPOSITORY} for each release
# candidate. Do not edit by hand.
class ChauffeurNext < Formula
  desc "Judgment engine for coding agents (release candidates)"
  homepage "${REPOSITORY}"
  license "MIT"

  on_macos do
${platforms("macos", release, sums, downloads)}
  end

  on_linux do
${platforms("linux", release, sums, downloads)}
  end

  def install
    bin.install "bin/chauffeur" => "chauffeur-next"
    pkgshare.install Dir["share/chauffeur/*"]
  end

  def caveats
    <<~EOS
      chauffeur-next keeps its own socket and its configuration in
      ~/.config/chauffeur-next/, so an installed chauffeur keeps working.

      Jev answers with TYPESAFE_API_KEY from the daemon's environment. To run
      the daemon at login, put the key in
      ~/.homebrew/services/chauffeur-next.env:
        TYPESAFE_API_KEY=...
      then start the service:
        brew services start chauffeur-next

      For OpenCode, add the adapter to "plugins" in opencode.jsonc:
        "plugins": ["#{opt_pkgshare}/opencode"]
    EOS
  end

  service do
    run [opt_bin/"chauffeur-next", "daemon", "run"]
    keep_alive true
    log_path var/"log/chauffeur-next.log"
    error_log_path var/"log/chauffeur-next.log"
  end

  test do
    assert_match "chauffeur-next #{version}", shell_output("#{bin}/chauffeur-next version")

    # A stand-in for Jev answers, so the shipped nudge runs without a key.
    (testpath/"config/chauffeur-next/models.json").write <<~JSON
      { "models": { "stand-in": { "format": "placeholder", "otherwise": { "yes": 0.94, "no": 0.06 } } },
        "tiers": { "system-one": ["stand-in"] } }
    JSON
    socket = testpath/"run/daemon.sock"
    ENV["XDG_CONFIG_HOME"] = (testpath/"config").to_s
    ENV["CHAUFFEUR_SOCKET"] = socket.to_s
    daemon = spawn bin/"chauffeur-next", "daemon", "run"
    begin
      50.times do
        break if socket.exist?

        sleep 0.1
      end
      event = <<~JSON
        { "event": "tool.after", "session": "s1", "tool": "shell",
          "input": { "command": "git commit -m 'fixed stuff'" } }
      JSON
      assert_match "message.append", pipe_output("#{bin}/chauffeur-next emit", event, 0)
    ensure
      Process.kill "TERM", daemon
      Process.wait daemon
    end
  end
end
`
}

if (process.argv[1] && resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  const [release, sumsPath, downloads] = process.argv.slice(2)

  if (!release || !sumsPath) throw new Error("usage: homebrew.mjs VERSION SHA256SUMS [DOWNLOADS_URL]")

  process.stdout.write(formula(release, parseSums(readFileSync(sumsPath, "utf8")), downloads))
}
