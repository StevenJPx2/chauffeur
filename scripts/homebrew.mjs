#!/usr/bin/env node
// The Homebrew formula for a release, rendered from its SHA256SUMS:
//
//   node scripts/homebrew.mjs 0.2.0 dist/SHA256SUMS > Formula/chauffeur.rb
//
// Every target's checksum comes from the same run that built the tarballs,
// so the formula is generated, never edited by hand.

import { readFileSync } from "node:fs"
import { resolve } from "node:path"
import { fileURLToPath } from "node:url"
import { tarballName } from "./package.mjs"

const REPOSITORY = "https://github.com/StevenJPx2/chauffeur"

/** Homebrew's OS and CPU blocks for each target, in the order they render. */
const PLATFORMS = [
  { os: "macos", cpu: "arm", target: "darwin-arm64" },
  { os: "macos", cpu: "intel", target: "darwin-x64" },
  { os: "linux", cpu: "arm", target: "linux-arm64" },
  { os: "linux", cpu: "intel", target: "linux-x64" },
]

/** `SHA256SUMS` as a map from file name to checksum. */
export function parseSums(text) {
  const sums = new Map()

  for (const line of text.split("\n").filter((line) => line.trim() !== "")) {
    const match = line.match(/^([0-9a-f]{64}) [ *]?(\S+)$/)

    if (!match) throw new Error(`not a SHA256SUMS line: ${line}`)
    sums.set(match[2], match[1])
  }

  return sums
}

export function formula(release, sums) {
  if (!/^\d+\.\d+\.\d+$/.test(release)) throw new Error(`a formula needs a stable version, not ${release}`)

  const block = (os) =>
    PLATFORMS.filter((platform) => platform.os === os)
      .map(({ cpu, target }) => {
        const name = tarballName(release, target)
        const sha256 = sums.get(name)

        if (!sha256) throw new Error(`SHA256SUMS has no ${name}`)

        return [
          `    on_${cpu} do`,
          `      url "${REPOSITORY}/releases/download/v${release}/${name}"`,
          `      sha256 "${sha256}"`,
          "    end",
        ].join("\n")
      })
      .join("\n")

  return `# Generated by scripts/homebrew.mjs in ${REPOSITORY} for each release.
# Do not edit by hand.
class Chauffeur < Formula
  desc "Rides along with your OpenCode agent and steps in when it matters"
  homepage "${REPOSITORY}"
  version "${release}"
  license "MIT"

  on_macos do
${block("macos")}
  end

  on_linux do
${block("linux")}
  end

  def install
    bin.install "bin/chauffeur"
    pkgshare.install Dir["share/chauffeur/*"]
    # The plugin OpenCode loads: it names opt paths, which follow upgrades,
    # where the bundle's own location is the Cellar path cleanup removes.
    (pkgshare/"opencode-plugin.js").write <<~JS
      process.env.CHAUFFEUR_BIN ??= "#{opt_bin}/chauffeur"
      process.env.CHAUFFEUR_SKILLS_DIR ??= "#{opt_pkgshare}/skills"
      const plugin = await import("#{opt_pkgshare}/dist/index.mjs")
      export const ChauffeurRpc = plugin.ChauffeurRpc
      export default plugin.default
    JS
  end

  def caveats
    <<~EOS
      Load the plugin in OpenCode, then restart it:
        chauffeur setup opencode

      The plugin starts the daemon with TYPESAFE_API_KEY from OpenCode's
      environment. To run it at login instead, put the key in
      ~/.homebrew/services/chauffeur.env and start the service:
        chauffeur setup opencode --service
        brew services start chauffeur

      After upgrading, restart the service (if enabled) and OpenCode:
        brew services restart chauffeur
    EOS
  end

  service do
    run [opt_bin/"chauffeur", "daemon"]
    keep_alive true
    environment_variables CHAUFFEUR_SKILLS_DIR: opt_pkgshare/"skills",
                          CHAUFFEUR_MANAGED:    "brew"
    log_path var/"log/chauffeur.log"
    error_log_path var/"log/chauffeur.log"
  end

  test do
    assert_match version.to_s, shell_output("#{bin}/chauffeur --version")
    assert_match "goal: 4 rule(s)",
      shell_output("#{bin}/chauffeur skill validate #{pkgshare}/skills/rulebooks/goal.json")
    assert_path_exists pkgshare/"dist/index.mjs"
  end
end
`
}

if (process.argv[1] && resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  const [release, sumsPath] = process.argv.slice(2)

  if (!release || !sumsPath) throw new Error("usage: homebrew.mjs VERSION SHA256SUMS")

  process.stdout.write(formula(release, parseSums(readFileSync(sumsPath, "utf8"))))
}
